import type { QuizFile } from '../../../quizFile'
import data from './referenceMeetData'

// One whole meet as it was scored and as its statistician worked it out, for checking stats against
// figures somebody else produced.
//
// `quizzes` are the meet's scoresheets as quiz files: two divisions, prelims, the two intermediates
// (X and Y), the elimination brackets and a consolation bracket with its round robin. No Finals
// sheet survives. The other tables are the statistician's workbook: its row for each team and each
// quizzer in each quiz, its quizzer standings, its prelim standings, and the order its teams were
// re-ranked into after the intermediates.
//
// Every team and quizzer name is made up, the same made-up name standing for the same real one
// throughout. The data file is generated by a script kept outside the repository with the source,
// which holds real names; regenerate it there rather than editing it.
//
// Known limits of the source:
// * Five sheets hold slips made on the day (`SHEETS_WITH_SLIPS`): they have validation errors, and
//   the workbook's figures for them are the scores as they stand.
// * The workbook ranks teams level on placement points by total score, then fewest errors, with no
//   head-to-head.
// * The workbook has team rows for prelims and the intermediates only (123 rows), and none for the
//   consolation bracket.
// * Its re-rank lists each team's new place and old place; the points behind it were lost.
// * Two quizzers are missing from its standings, and it has no row for a seat left unnamed.

export interface ReferenceQuiz {
  /** The sheet's name: `D1Q4` is division 1 quiz 4, `D2cQA` division 2's consolation quiz A */
  sheet: string
  file: QuizFile
}

export interface ReferenceTeamRow {
  sheet: string
  team: string
  place: number
  score: number
  placementPoints: number
  errors: number
}

/** Correct answers by question type, in the workbook's order */
export const REFERENCE_TYPES = ['REF', 'FTV', 'INT', 'MA', 'Q', 'SIT'] as const

export interface ReferenceQuizzerRow {
  sheet: string
  team: string
  quizzer: string
  points: number
  errors: number
  jumps: number
  types: number[]
}

export interface ReferenceQuizzerStanding {
  division: string
  /** Listed apart: the quizzer's team played in the consolation bracket */
  consolation: boolean
  place: number
  team: string
  quizzer: string
  /** As the workbook shows it, to two decimals */
  average: number
  points: number
  errors: number
  jumps: number
  /** The quizzes the quizzer's team played */
  quizzes: number
  types: number[]
  typesComplete: boolean
}

export interface ReferenceTeamStanding {
  division: string
  rank: number
  team: string
  placementPoints: number
  score: number
  errors: number
  quizzes: number
}

export interface ReferenceRerank {
  division: string
  newPlace: number
  oldPlace: number
  team: string
}

export interface ReferenceMeet {
  quizzes: ReferenceQuiz[]
  teamRows: ReferenceTeamRow[]
  quizzerRows: ReferenceQuizzerRow[]
  quizzerStandings: ReferenceQuizzerStanding[]
  prelimStandings: ReferenceTeamStanding[]
  rerank: ReferenceRerank[]
}

export const referenceMeet = JSON.parse(data) as ReferenceMeet

/** The sheets with validation errors: slips made on the day, counted by the workbook as scored */
export const SHEETS_WITH_SLIPS = ['D2Q6', 'D2Q7', 'D2cQE', 'D2cQh', 'D2cQp']
